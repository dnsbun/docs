#!/usr/bin/env python3

import argparse
import json
import os
from pathlib import Path
from urllib.parse import urlparse


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Render the public PostHog configuration for the docs site."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/javascripts/posthog-config.js"),
    )
    return parser.parse_args()


def require_environment_variable(name: str) -> str:
    value = os.environ.get(name, "").strip()
    if not value:
        raise SystemExit(f"{name} must be set")
    return value


def main() -> None:
    args = parse_args()
    project_token = require_environment_variable("POSTHOG_PROJECT_TOKEN")
    api_host = require_environment_variable("POSTHOG_HOST").rstrip("/")

    if not project_token.startswith("phc_"):
        raise SystemExit("POSTHOG_PROJECT_TOKEN must be a PostHog project token")

    parsed_host = urlparse(api_host)
    if (
        parsed_host.scheme != "https"
        or not parsed_host.netloc
        or parsed_host.path
        or parsed_host.params
        or parsed_host.query
        or parsed_host.fragment
    ):
        raise SystemExit("POSTHOG_HOST must be an HTTPS origin without a path")

    config = {
        "apiHost": api_host,
        "projectToken": project_token,
    }
    rendered = (
        "// Generated by scripts/render-posthog-config.py.\n"
        f"window.__DNSBUN_POSTHOG_CONFIG__ = Object.freeze({json.dumps(config)});\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
